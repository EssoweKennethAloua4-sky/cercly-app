const dicts: Record<Locale, Dict> = { fr, en }

interface I18n {
  locale: Locale
  setLocale: (l: Locale) => void
  t: (k: Key | string, vars?: Record<string, string | number>) => string
}

const Ctx = createContext<I18n | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLoc] = useState<Locale>(() => (localStorage.getItem('cercly.locale') === 'en' ? 'en' : 'fr'))
  const setLocale = useCallback((l: Locale) => {
    setLoc(l)
    localStorage.setItem('cercly.locale', l)
    document.documentElement.lang = l
  }, [])
  const t = useCallback(
    (k: string, vars?: Record<string, string | number>) => {
      const s = (dicts[locale] as Record<string, string>)[k]
      if (!s) return k
      return s.replace(/\{(\w+)\}/g, (_, n: string) => String(vars?.[n] ?? ''))
    },
    [locale],
  )
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n(): I18n {
  const v = useContext(Ctx)
  if (!v) throw new Error('I18nProvider manquant')
  return v
}
